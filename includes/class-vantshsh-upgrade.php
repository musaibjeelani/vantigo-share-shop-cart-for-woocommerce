<?php
/** Upgrade storage and saved placements from pre-review builds. */
if ( ! defined( 'ABSPATH' ) ) {
    exit;
}

class VANTSHSH_Upgrade {
    /** Copy known settings without overwriting choices already saved in this build. */
    public static function migrate_options( $defaults ) {
        foreach ( array_keys( $defaults ) as $key ) {
            $legacy_key = 'sscw_' . substr( $key, strlen( 'vantshsh_' ) );
            $legacy_value = get_option( $legacy_key, null );
            if ( null !== $legacy_value && false === get_option( $key ) ) {
                add_option( $key, $legacy_value );
            }
        }
    }

    /** Preserve hashes so links generated by previous review builds keep working. */
    public static function migrate_carts() {
        global $wpdb;
        $old_table = $wpdb->prefix . 'sscw_shared_carts';
        $new_table = $wpdb->prefix . 'vantshsh_shared_carts';
        // phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
        $exists = $wpdb->get_var( $wpdb->prepare( 'SHOW TABLES LIKE %s', $wpdb->esc_like( $old_table ) ) );
        if ( $old_table !== $exists ) {
            return true;
        }
        // Identifiers come exclusively from the WordPress table prefix and fixed suffixes.
        // Omit auto-increment IDs so an existing new table cannot hide unrelated old rows.
        // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared
        $result = $wpdb->query( 'INSERT IGNORE INTO `' . esc_sql( $new_table ) . '` (cart_hash, cart_data, created_at, expires_at, share_count, views_count, restored_count, cart_total, user_id) SELECT cart_hash, cart_data, created_at, expires_at, share_count, views_count, restored_count, cart_total, user_id FROM `' . esc_sql( $old_table ) . '`' );
        // phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
        return false !== $result;
    }

    /** Change only this plugin's old Elementor widget type, preserving its settings. */
    public static function migrate_element_tree( $elements ) {
        if ( ! is_array( $elements ) ) {
            return $elements;
        }
        foreach ( $elements as &$element ) {
            if ( ! is_array( $element ) ) {
                continue;
            }
            if ( isset( $element['widgetType'] ) && 'sscw_share_cart_widget' === $element['widgetType'] ) {
                $element['widgetType'] = 'vantshsh_share_cart_widget';
            }
            if ( isset( $element['widgetType'], $element['settings']['shortcode'] ) && 'shortcode' === $element['widgetType'] ) {
                $element['settings']['shortcode'] = self::legacy_shortcodes( $element['settings']['shortcode'] );
            }
            if ( isset( $element['widgetType'], $element['settings']['editor'] ) && 'text-editor' === $element['widgetType'] ) {
                $element['settings']['editor'] = self::legacy_shortcodes( $element['settings']['editor'] );
            }
            if ( isset( $element['elements'] ) ) {
                $element['elements'] = self::migrate_element_tree( $element['elements'] );
            }
        }
        unset( $element );
        return $elements;
    }

    public static function migrate_elementor() {
        global $wpdb;
        $last_id = 0;
        do {
            // Read bounded batches and update through the metadata API to clear caches.
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
            $rows = $wpdb->get_results( $wpdb->prepare( "SELECT meta_id, post_id, meta_value FROM {$wpdb->postmeta} WHERE meta_key = %s AND meta_id > %d AND (meta_value LIKE %s OR meta_value LIKE %s OR meta_value LIKE %s) ORDER BY meta_id ASC LIMIT 100", '_elementor_data', $last_id, '%' . $wpdb->esc_like( 'sscw_share_cart_widget' ) . '%', '%' . $wpdb->esc_like( '[share_shop_cart' ) . '%', '%' . $wpdb->esc_like( '[share_cart_url' ) . '%' ) );
            if ( ! is_array( $rows ) ) {
                return false;
            }
            foreach ( $rows as $row ) {
                $last_id = (int) $row->meta_id;
                $data = json_decode( $row->meta_value, true );
                if ( ! is_array( $data ) ) {
                    continue;
                }
                $updated = self::migrate_element_tree( $data );
                if ( $data !== $updated ) {
                    if ( ! update_metadata_by_mid( 'post', $row->meta_id, wp_json_encode( $updated ) ) ) {
                        return false;
                    }
                    delete_post_meta( $row->post_id, '_elementor_css' );
                }
            }
        } while ( count( $rows ) === 100 );
        return true;
    }

    /** Keep saved shortcode placements working without registering generic aliases. */
    public static function legacy_shortcodes( $content ) {
        if ( ! is_string( $content ) ) {
            return $content;
        }
        return preg_replace_callback(
            '/(?<!\[)\[(\/?)(share_shop_cart|share_cart_url)(?=[\s\]\/])/',
            static function( $match ) {
                if ( shortcode_exists( $match[2] ) ) {
                    return $match[0];
                }
                return '[' . $match[1] . ( 'share_shop_cart' === $match[2] ? 'vantshsh_share_cart' : 'vantshsh_cart_url' );
            },
            $content
        );
    }
}
